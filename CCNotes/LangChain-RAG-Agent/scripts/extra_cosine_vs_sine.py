section("3｜★致命问题一：sin 在 0°~180° 不单调，两两撞车")
# #################################################################

print("  两个向量的夹角 θ 在 0°（同向）到 180°（反向）之间。把两个函数全列出来：\n")
print(f"  {'θ':>5}{'cos θ':>11}{'sin θ':>11}     cos 能区分吗   sin 能区分吗")
for deg in range(0, 181, 15):
    r = math.radians(deg)
    c, s = math.cos(r), math.sin(r)
    c_note = "唯一值"
    s_note = "唯一值" if deg == 90 else "与另一个角撞车"
    print(f"  {deg:>5}{c:>11.4f}{s:>11.4f}     {c_note:<14}{s_note}")

print(f"""
  ★ 看出区别了吗：

      cos θ：1.00 → 0.00 → -1.00   **严格单调递减**
             每个角度对应唯一的值，一一对应，信息不丢失。

      sin θ：0.00 → 1.00 → 0.00    **先升后降的拱形**
             除了 90° 那一个点，**其他角度全部两两撞车**。

  撞车有多严重？sin θ = sin(180° − θ)，所以：
""")
for a, b in ((0, 180), (30, 150), (60, 120), (89, 91)):
    ra, rb = math.radians(a), math.radians(b)
    print(f"      θ={a:>3}° 和 θ={b:>3}°  →  sin 都是 {math.sin(ra):.4f}"
          f"  但 cos 是 {math.cos(ra):>7.4f} vs {math.cos(rb):>7.4f}")

print("""
  翻译成检索的语言，看第一行：

      sin 0°   = 0    两个向量**完全同向**（一模一样的两句话）
      sin 180° = 0    两个向量**完全反向**（意思正好相反）

  **一模一样和正好相反，拿到同一个分数。** 这是致命的。

  第二行同样荒谬：偏 30°（还很像）和偏 150°（几乎反了）
  在 sin 眼里毫无区别。

  ★ 用 sin 排序 = 把 0°~90° 和 90°~180° 这两半**叠在一起看**，
    一个"分数"对应两种截然相反的情况，系统根本没法判断该给谁排前面。

  ★ 术语：cos 在 [0°, 180°] 上是**一一映射**（双射），sin 不是。
    相似度指标必须能排序，所以必须单调——cos 满足，sin 不满足。
""")


