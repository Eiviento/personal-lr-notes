section("4｜次要问题：高维里 sin 的动态范围被压扁")
# #################################################################

print("""  这一节是**次要**的——真正判死刑的是上一节。但既然我们的向量是 512 维
  而不是 2 维，高维带来的影响还是值得看看。

  高维空间有个反直觉的性质叫**集中现象**（concentration of measure）：

      **在很高的维度里，随便抓两个随机向量，它们几乎总是接近垂直的。**

  为什么？直觉版解释：夹角由所有维度的贡献共同决定。维度越多，
  各维度的正负贡献越容易互相抵消，最后净结果趋近于 0（也就是 90°）。

  实测（每个维度随机取 3000 对不相关的向量，看 cos 和 sin 各自的分布）：
""")

rng = np.random.default_rng(0)
print(f"  {'维度':>6}{'cos 均值':>11}{'cos 标准差':>13}{'sin 均值':>11}{'sin 标准差':>13}")
for d in (2, 3, 10, 100, 512):
    cs, ss = [], []
    for _ in range(3000):
        x, y = rng.normal(size=d), rng.normal(size=d)
        c = float(x @ y) / (np.linalg.norm(x) * np.linalg.norm(y))
        cs.append(c)
        ss.append(math.sqrt(max(0.0, 1 - c * c)))
    cs, ss = np.array(cs), np.array(ss)
    print(f"  {d:>6}{cs.mean():>11.4f}{cs.std():>13.4f}{ss.mean():>11.4f}{ss.std():>13.4f}")

print("""
  ★ 看标准差那两列，这就是"集中现象"：

      维度 2   ：cos 标准差 0.7088 —— 从 -1 到 1 到处都是
      维度 512 ：cos 标准差 0.0435 —— 全部挤在 0 附近

    维度越高，不相关的向量越趋于垂直（cos → 0）。

  那这对 sin 意味着什么？看 512 维这一行：

      不相关文档：cos ≈ 0      →  sin ≈ 1.0000（标准差只有 0.0013，挤成一条线）
      相关文档  ：cos = 0.6769 →  sin = 0.7361（项目实测的那一对）

    sin 在这两种情况的差距：1.0000 − 0.7361 = **0.2639**
    cos 在这两种情况的差距：0.6769 − 0.0000 = **0.6769**

    cos 拉开的差距是 sin 的 2.6 倍。为什么？因为 sin = √(1−cos²)
    在 cos = 0 处的**斜率是 0**（一个平顶），这一带 cos 怎么变，sin 几乎不动：

        cos 0.00 → sin 1.000000   斜率 0.000000   ← 完全平
        cos 0.01 → sin 0.999950   斜率 0.010001
        cos 0.05 → sin 0.998749   斜率 0.050063
        cos 0.10 → sin 0.994987   斜率 0.100504

  ★★★ 但这里必须说句公道话（诚实比"论据多"重要）★★★

    上面这套"sin 分辨不出东西"的说法，**只对了一半**：

    sin 的动态范围确实被压扁了（0.264 vs 0.677），
    但**噪声也被同等压扁了**——不相关文档的标准差从 0.0435 掉到 0.0013。
    信号和噪声一起缩小，**排序本身还是成立的**。

    所以准确的说法是：**高维不是 sin 的死因，只是让它看起来更不顺手。**
    sin 真正的死因是上一节的**非单调**——那一条单独就足以判死刑，
    不需要这一节帮忙。

  ★ 这一节的真正价值是另一件事：**将来遇到"分数被压扁"的指标，
    先别急着扔掉，看看噪声是不是也被压扁了。**
    信号噪声比（SNR）才是判断指标能不能用的标准，不是数值范围的大小。
""")

print("""
  ── 顺带一个结构性原因：sin 在 n 维里没有独立的算法 ──

  在 3 维，你可以用叉积算     |a × b| = |a| |b| sin θ。
  但**只有 3 维和 7 维能定义出性质完整的叉积**——512 维没有叉积这个东西。

  n 维里想算 sin θ，只能绕道：

      sin θ = √(1 − cos²θ)

  看出来了吗？**得先算出 cos 才能得到 sin。**
  而 cos 是点积直接给的（下一节）。**sin 永远是二手数据。**
""")


