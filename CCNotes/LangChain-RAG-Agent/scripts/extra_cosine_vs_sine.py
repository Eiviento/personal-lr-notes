section("5｜为什么 cos 是『天然』的那个：它就长在点积里")
# #################################################################

print("""  这不是"我们选了 cos"，而是"cos 本来就在那儿"。

  点积有两个等价的定义：

      代数定义（算法）：  a·b = Σ aᵢbᵢ            ← 对应位置相乘再相加
      几何定义（含义）：  a·b = |a| |b| cos θ     ← 长度 × 长度 × 夹角余弦

  同一个东西的两种说法。把几何定义两边一除：

                  a·b
      cos θ = ───────────          ← 余弦相似度的公式
               |a| |b|

  ★ **余弦相似度不是"发明"出来的指标，它就是点积的几何定义移项的结果。**
    只要你想用点积（而点积是向量运算里最省事、最快的操作），
    你手上天然拿到的就是 cos。

  反过来看 sin 的处境：

      - 它不在点积里 —— 点积里没有 sin 的位置
      - n 维里没有叉积可以算它
      - 只能 cos² + sin² = 1 绕道从 cos 推导

  ★ 一句话：**cos 是点积的亲儿子，sin 是点积的远房亲戚。**
    检索要比几百万次，当然用顺手、便宜、信息不丢的那个。

  顺带说性能：余弦要开两次根号；归一化之后（见 extra_cosine_similarity.md）
  **分母变成 1，就只剩一次点积**。
  如果指标里带 sin，还得先算 cos 再平方再开根，反而更贵。
""")


