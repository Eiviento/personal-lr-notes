section("2｜几何：它是同一个角的两个投影")
# #################################################################

print("""  想象单位圆（半径为 1 的圆）上有个点，从 x 轴正方向逆时针转了 θ 度：

        y
        ↑
      1 ┤      ● (cos θ, sin θ)
        │     ╱│
        │    ╱ │ ← sin θ（竖直投影）
        │   ╱  │
        │  ╱   │
        └─┴────┴────→ x
          0  cos θ
             ↑
             水平投影

  这一个点，两个投影：
      cos θ = 投影到 x 轴的长度
      sin θ = 投影到 y 轴的长度

  **两个数描述的是同一个方向，只是一个横着量、一个竖着量。**

  把它们当"相似度"用的话：
      - cos：θ=0 时最大（=1）→ 同向得满分
      - sin：θ=0 时最小（=0）→ 同向得零分

  ★ 光看这一条，cos 就已经赢了：**我们想要"越像分越高"，
    而"完全一样"这件事在 cos 里天然是最高分，在 sin 里是最低分。**
    用一个「最相似 → 0 分」的指标去排序，逻辑是拧着的。

  但这还不是 sin 真正的死穴。往下看。
""")


