print("""
  中文"余弦"两个字拆开就是答案：**余角的弦**——余角的正弦。

      cos θ  =  sin(90° − θ)
      └┬─┘     └────┬────┘
      余弦        余角的正弦

  （推而广之，"余切"=余角的正切，"余割"=余角的正割，都是同一套命名法。）

  ★ 所以"为什么不叫正弦相似度"这个问题，第一层答案是：
    **它本来就是正弦**——只不过量的是"余角"。
    用 sin θ 还是用 cos θ，本质上是"从哪根轴开始量角度"的问题，
    不是两套不同的算法。

  但这就带出一个更实际的问题：**既然只是换个轴量，那换个轴会怎样？**
  第 3 节告诉你：换完就废了——而且废在一个你可能没想到的地方。
""")


