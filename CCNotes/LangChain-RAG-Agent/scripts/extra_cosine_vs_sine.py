section("6｜那 sin 还有用吗？")
# #################################################################

print("""  有，但不是用来排序的。

  它的真正含义是**"偏离共线的程度"**（正交程度 / 不相关的程度）：

      sin θ = 0   →  两个向量共线（同向或反向，完全相关）
      sin θ = 1   →  两个向量正交（完全不同，毫无关系）

  在 3 维几何里它有大用：

      - 叉积的模 |a×b| = |a||b| sin θ → 平行四边形面积
      - 三角形面积 = ½ |a×b|
      - 点到直线的距离（用叉积算）

  但在**检索排序**里它有几个绕不过去的坎，前面都讲过了：

      1. ★**不单调** → 完全同向和完全反向同分（第 3 节）← 这一条就够了
      2. 方向反了 → sin 越小越像，跟"相似度"的语义拧着（第 2 节）
      3. 高维里动态范围被压扁（第 4 节）← 次要，不足以单独判死刑
      4. n 维没有叉积 → 想算它得先算 cos，永远是二手数据（第 5 节）

  ★ 所以准确的回答是：

      **不是"没人做正弦相似度"，而是 sin 在检索这个用途上不成立。**
      sin 不是 cos 的竞争算法——它俩本来就描述同一个角，
      只是一个（cos）在 0°~180° 上单调、能排序，
      另一个（sin）是拱形的，把"一样"和"相反"判成了同一分。**
""")

