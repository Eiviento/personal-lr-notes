section("8｜为什么要归一化：点积会被『长度』带偏（本课重点）")
# #################################################################

print(f"""  前面说过：**方向和长度是两件独立的事**。现在看这个区别有多大威力。

  造三个向量，**方向完全一样**，只是长度不同：

      a  = {a}                        ← |a| = 5
      b  = {b_same}                      ← 就是 a 的 2 倍，|b| = 10
      c  = [300, 400]                 ← 就是 a 的 100 倍，|c| = 500

  它们指向**完全相同**的方向，所以"相似度"理应完全一样。看实际数字：
""")
c_long = [300, 400]
print(f"  {'对比':<16}{'点积':>12}{'余弦':>10}   说明")
for name, other in (("a vs b (2倍)", b_same), ("a vs c (100倍)", c_long)):
    print(f"  {name:<16}{dot(a, other):>12}{cosine(a, other):>10.4f}   ← 点积变了，余弦没变")

print("""
  ★ 看到了吗：

      - **点积从 50 涨到 2500**（差 50 倍！）—— 它被"长度"污染了
      - **余弦始终是 1.0** —— 因为分母把长度约掉了，只剩方向

  现在设想你是个检索系统，用点积给文档打分：

      文档A：和查询很相关，但向量长度是 5    → 点积 50
      文档B：和查询不太相关，但向量长度 500  → 点积可能 500

  结果 **文档B 排在前面**。系统选错了，而且错得莫名其妙——看起来打分很高。

  ★ 这就是归一化的全部意义：**先把长度统一成 1，让分数只反映方向。**
    归一化之后，点积不再被长度干扰，可以放心地直接当余弦用。

  一句话记忆：**不归一化的点积 = 方向分 × 长度分；归一化把它变成纯方向分。**
""")


