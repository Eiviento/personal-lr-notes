# ── 手写点积和模长（不用任何库，方便你看清每一步） ──────────────
def dot(a, b):
    """点积：对应位置相乘，再全部加起来"""
    return sum(x * y for x, y in zip(a, b))


def norm(a):
    """模长（向量长度）：各分量平方和，再开根号"""
    return math.sqrt(sum(x * x for x in a))


def cosine(a, b):
    """余弦相似度 = 点积 ÷ (两边模长相乘)"""
    return dot(a, b) / (norm(a) * norm(b))


