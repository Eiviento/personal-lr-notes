section("4｜余弦相似度：只看方向，不看长短")
# #################################################################

print("""  现在回答"什么是余弦相似度"。

  两个箭头之间有个**夹角 θ**。余弦相似度就是去算这个角的余弦值 cos θ：

                  a·b           点积
      cos θ = ───────────  =  ──────────────
               |a| × |b|       模长 × 模长

  ★ 关键理解：分子是点积，分母是"两边长度相乘"。
    分母的作用是**把长度因素除掉**，让结果只剩下"方向对不对"。

  几何意义（高中知识，复习一下）：

      cos 0°  = 1     两个箭头完全同向     → 最相似
      cos 90° = 0     两个箭头垂直         → 毫无关系
      cos 180° = -1   两个箭头完全反向     → 最不相似
""")


