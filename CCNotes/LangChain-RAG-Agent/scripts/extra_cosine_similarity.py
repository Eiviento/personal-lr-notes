section("6｜现在回答：为什么归一化后点积 == 余弦")
# #################################################################

print("""  先说什么叫**归一化**（normalize）：

      把一个向量除以它自己的模长。

      â = a / |a|        （上加小帽子表示"处理过的 a"）

  效果：新向量的模长**必然等于 1**（方向不变，长度拉到 1）。

      验证：|â| = |a / |a|| = |a| / |a| = 1

  这种长度恰好为 1 的向量叫"单位向量"。

  ── 然后看余弦的公式会发生什么 ──

      cos θ = (â · b̂) / (|â| × |b̂|)

  既然 |a|̂ 和 |b̂| 都等于 1，分母就是 1 × 1 = 1：

      cos θ = (â · b̂) / 1 = â · b̂

  ★ 这就是那句话的全部来历：

      **归一化之后，两个向量的点积，就是余弦相似度。**
      因为余弦公式的分母被归一化变成了 1，除了个寂寞。

  ── 为什么大家喜欢这个结论？──

      余弦相似度要算 1 次点积 + 2 次开根号（开根号慢）。
      归一化之后只要 1 次点积。向量库动辄比几百万次，
      省掉两次开根号是实打实的性能收益。

  所以工程上的标准做法是：**入库前就归一化好**，检索时就只用算点积。
  项目的 phase4_1_rag.py:133 干的就是这件事（第 10 节看代码）。
""")


section("7｜实测：随机向量验证这个等式")

import numpy as np

rng = np.random.default_rng(42)  # 固定种子，保证每次跑结果一样
print("  随机造 5 组 512 维向量（和项目里 BGE 的维度一致），逐组对比：\n")
print(f"  {'':>4}{'点积':>12}{'余弦':>14}{'归一化后点积与余弦之差':>20}")
for i in range(5):
    x = rng.normal(size=512)
    y = rng.normal(size=512)
    d = float(x @ y)
    c = d / (np.linalg.norm(x) * np.linalg.norm(y))
    # 归一化后再算点积
    d_norm = float((x / np.linalg.norm(x)) @ (y / np.linalg.norm(y)))
    print(f"  {i + 1:>3} {d:>14.6f}{c:>14.6f}{abs(d_norm - c):>14.2e}")

print("""
  最后一列是 0 或者 1e-17 这种级别——那是**浮点数的舍入误差**，
  不是算法差异。数学上它们是同一个数，计算机里因为存储精度会差最后几位。

  ★ 一句话：**"相等"在数学上成立，在计算机里差个 1e-17，可以忽略。**
""")


