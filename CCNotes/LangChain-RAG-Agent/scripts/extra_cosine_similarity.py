section("9｜真实数据：BGE 原始向量的模长确实各不相同")
# #################################################################

print("  上面是手造的例子。真实 embedding 模型的输出，长度也真的不一样。")
print("  直接从项目的 BGE 模型里取**未归一化**的原始向量（CLS 池化那一步）：\n")

from phase4_1_rag import MODEL_DIR, LocalBertEmbedding  # noqa: E402

emb = LocalBertEmbedding(str(MODEL_DIR), pooling="cls")


def raw_vector(text: str) -> np.ndarray:
    """复刻 LocalBertEmbedding 的前两步（分词 → ONNX 推理），但**不做归一化**"""
    ids, mask = emb.tokenizer.encode(text)
    outs = emb.session.run(
        None,
        {
            "input_ids": ids[None, :],
            "attention_mask": mask[None, :],
            "token_type_ids": np.zeros_like(ids)[None, :],
        },
    )
    return outs[0][0][0]  # [CLS] 向量


texts = ["设备位置通过水表阀门上报", "水表阀门模板协议", "环境监测数据上传"]
raws = [raw_vector(t) for t in texts]

print(f"  {'文本':<16}{'原始模长':>10}{'归一化后模长':>14}")
for t, r in zip(texts, raws):
    print(f"  {t:<16}{np.linalg.norm(r):>10.4f}{np.linalg.norm(r / np.linalg.norm(r)):>14.4f}")

print("""
  ★ 三个原始模长 {:.4f} / {:.4f} / {:.4f} —— **各不相同**。
    这就是为什么模型输出后必须补一步归一化（在 phase4_1_rag.py:133）。

  归一化那一步走完，模长全变成 1.0000。之后：
""".format(*(np.linalg.norm(r) for r in raws)))

qa, da = raws[0], raws[1]
print("  同一对文本，两种算法的结果：")
print(f"    原始向量  点积 = {qa @ da:>8.4f}      余弦 = {(qa @ da) / (np.linalg.norm(qa) * np.linalg.norm(da)):>8.4f}   ← 差很远")
nq, nd = qa / np.linalg.norm(qa), da / np.linalg.norm(da)
print(f"    归一化后  点积 = {nq @ nd:>8.4f}      余弦 = {(nq @ nd) / (np.linalg.norm(nq) * np.linalg.norm(nd)):>8.4f}   ← 一致了")

print("""
  ★ 诚实说明：本例里按点积排序和按余弦排序**碰巧结果一样**，
    因为这两句的模长（6.55 vs 7.65）差别还不算大。
    但数值尺度完全不同（33.94 vs 0.68）——只要文档一多、长短差距一大，
    排序就会翻车。归一化是为了**消除这个隐患**，不是修一个已经出现的 bug。
""")


